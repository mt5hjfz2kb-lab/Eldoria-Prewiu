#if UNITY_EDITOR
using System;
using System.IO;
using Eldoria.Experimentos.ValoriaModular25D;
using UnityEditor;
using UnityEditor.Build.Reporting;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.SceneManagement;

namespace Eldoria.Experimentos.ValoriaModular25D.Editor
{
    /// <summary>
    /// Opt-in native verification; never writes into main scenes, saves or publishing channels.
    /// No QA status or screenshot is declared until these exact methods run in Unity.
    /// </summary>
    public static class Modular25DEditorTasks
    {
        public const string ScenePath =
            "Assets/Experimentos/ValoriaModular25D/Scenes/BastionI_Modular25D.unity";
        const string EvidencePath = "Artifacts/ValoriaModular25D/Native";
        static float sequenceNextAt;
        static int sequenceFrame;

        [MenuItem("Eldoria/Experimentos/Valoria modular 2.5D/Abrir Bastión I")]
        public static void Open()
        {
            EditorSceneManager.OpenScene(ScenePath,OpenSceneMode.Single);
        }

        [MenuItem("Eldoria/Experimentos/Valoria modular 2.5D/Validar escena aislada")]
        public static void AuditScene()
        {
            var scene=EditorSceneManager.OpenScene(ScenePath,OpenSceneMode.Single);
            int world=0,guard=0;
            foreach(var root in scene.GetRootGameObjects())
            {
                world+=root.GetComponentsInChildren<Modular25DWorld>(true).Length;
                foreach(var presenter in root.GetComponentsInChildren<Eldoria.Presentation.SlicePresenter>(true))
                    if(!presenter.enabled)guard++;
            }
            if(world!=1||guard!=1)
                throw new InvalidOperationException("Sandbox invalid: expected one modular world and one disabled SliceBoot guard; got "+world+"/"+guard);
            Debug.Log("[Modular25D] Scene topology PASS. This does NOT certify compilation/play/touch/art.");
        }

        [MenuItem("Eldoria/Experimentos/Valoria modular 2.5D/Capturar Unity real (PlayMode)")]
        public static void Capture()
        {
            if(!EditorApplication.isPlaying)
                throw new InvalidOperationException("Enter PlayMode first. Captures must be generated by real Unity render.");
            var world=UnityEngine.Object.FindFirstObjectByType<Modular25DWorld>();
            if(world==null||world.ViewCamera==null)throw new InvalidOperationException("Modular runtime world not loaded.");
            PlayerStateCapture(world,390,844,"portrait-390x844");
            PlayerStateCapture(world,1170,2532,"portrait-1170x2532");
            PlayerStateCapture(world,844,390,"landscape-844x390");
        }

        static void PlayerStateCapture(Modular25DWorld world,int width,int height,string label)
        {
            string folder=Path.GetFullPath(Path.Combine(UnityEngine.Application.dataPath,"..",EvidencePath));
            Directory.CreateDirectory(folder);
            string filename=Path.Combine(folder,label+"-"+DateTime.UtcNow.ToString("yyyyMMdd-HHmmss")+".png");
            var camera=world.ViewCamera;
            RenderTexture oldCamera=camera.targetTexture,oldActive=RenderTexture.active;
            var target=new RenderTexture(width,height,24,RenderTextureFormat.ARGB32);
            Texture2D texture=null;
            try
            {
                target.Create();
                camera.targetTexture=target;
                camera.Render();
                RenderTexture.active=target;
                texture=new Texture2D(width,height,TextureFormat.RGBA32,false);
                texture.ReadPixels(new Rect(0,0,width,height),0,0);
                texture.Apply();
                File.WriteAllBytes(filename,texture.EncodeToPNG());
                File.WriteAllText(filename+".provenance.txt",
                    "source=Unity Camera.Render real\nengine="+UnityEngine.Application.unityVersion+
                    "\nscene="+SceneManager.GetActiveScene().path+
                    "\ntimestamp_utc="+DateTime.UtcNow.ToString("o")+
                    "\nresolution="+width+"x"+height+
                    "\nstatus=unreviewed (world render only; screen-space HUD not included)\n");
                Debug.Log("[Modular25D] Captured AUTHENTIC Unity camera frame at "+filename);
            }
            finally
            {
                camera.targetTexture=oldCamera;
                RenderTexture.active=oldActive;
                if(texture!=null)UnityEngine.Object.DestroyImmediate(texture);
                target.Release();
                UnityEngine.Object.DestroyImmediate(target);
            }
        }

        [MenuItem("Eldoria/Experimentos/Valoria modular 2.5D/Grabar movimiento Unity (PlayMode, 90 fotogramas)")]
        public static void StartMotionEvidence()
        {
            if(!EditorApplication.isPlaying)
                throw new InvalidOperationException("Actual Unity PlayMode is required.");
            var world=UnityEngine.Object.FindFirstObjectByType<Modular25DWorld>();
            if(world==null)throw new InvalidOperationException("Missing running modular world.");
            sequenceFrame=0;
            sequenceNextAt=Time.realtimeSinceStartup;
            EditorApplication.update-=CaptureNextSequenceFrame;
            EditorApplication.update+=CaptureNextSequenceFrame;
        }

        static void CaptureNextSequenceFrame()
        {
            if(!EditorApplication.isPlaying){EditorApplication.update-=CaptureNextSequenceFrame;return;}
            var world=UnityEngine.Object.FindFirstObjectByType<Modular25DWorld>();
            if(world==null){EditorApplication.update-=CaptureNextSequenceFrame;return;}
            if(Time.realtimeSinceStartup<sequenceNextAt)return;
            sequenceNextAt=Time.realtimeSinceStartup+1f/12f;
            PlayerStateCapture(world,390,844,"motion-"+sequenceFrame.ToString("D3"));
            sequenceFrame++;
            if(sequenceFrame>=90)
            {
                EditorApplication.update-=CaptureNextSequenceFrame;
                Debug.Log("[Modular25D] 90 genuine Unity camera frames. Assemble into video separately; NOT a recorded device test.");
            }
        }

        [MenuItem("Eldoria/Experimentos/Valoria modular 2.5D/Compilar WebGL aislado")]
        public static void BuildIsolatedWebGL()
        {
            // The historical canonical World4X terrain gate is global. Only
            // the disposable Windows scratch has an additional narrowly scoped
            // prebuild condition for this exact scene/output combination.
            // Set and restore the Editor build scene list so the scoped guard
            // can independently prove this player is NOT the canonical world.
            AuditScene();
            var originalScenes=EditorBuildSettings.scenes;
            string outFolder=Path.GetFullPath(
                Path.Combine(UnityEngine.Application.dataPath,"..","Builds","ValoriaModular25D_WebGL"));
            Directory.CreateDirectory(outFolder);
            try
            {
                EditorBuildSettings.scenes=new[]{new EditorBuildSettingsScene(ScenePath,true)};
                BuildReport report=BuildPipeline.BuildPlayer(new BuildPlayerOptions {
                    scenes=new[]{ScenePath},
                    locationPathName=outFolder,
                    target=BuildTarget.WebGL,
                    options=BuildOptions.StrictMode
                });
                if(report.summary.result!=BuildResult.Succeeded ||
                   report.summary.totalErrors!=0 ||
                   !File.Exists(Path.Combine(outFolder,"index.html")))
                    throw new InvalidOperationException("Isolated WebGL build did not pass: "+
                        report.summary.result+" errors="+report.summary.totalErrors);
                Debug.Log("[Modular25D] Exact single-scene WebGL built at "+outFolder+
                    ". This does NOT prove a browser run or physical iPhone QA.");
            }
            finally
            {
                EditorBuildSettings.scenes=originalScenes;
            }
        }
    }
}
