const {chromium}=require('playwright');
(async()=>{
 const b=await chromium.launch({headless:true});
 const p=await b.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 await p.addInitScript(()=>{window.__testerReceived=[];window.__ELDORIA_TESTER_SUBMIT__=async r=>{window.__testerReceived.push(r);return true}});
 await p.goto('http://127.0.0.1:4173/tester-v0265/?testerqa=1',{waitUntil:'domcontentloaded'});
 await p.locator('[data-testid="tester-intro"]').waitFor({state:'visible'});
 await p.locator('[data-start]').click();
 await p.locator('[data-testid="tester-intro"]').waitFor({state:'detached'});
 await p.locator('[data-testid="tester-feedback"]').waitFor({state:'visible'});
 const core=await p.evaluate(()=>({game:!!window.ELDORIA_V023,tester:!!window.ELDORIA_TESTER,screen:window.ELDORIA_V023?.state?.().view,ctx:window.ELDORIA_TESTER?.context?.()}));
 if(!core.game||!core.tester||!core.ctx||core.ctx.testerVersion!=='0.26.5-test.1')throw Error('Tester/game runtime contract failed');
 await p.locator('[data-testid="tester-feedback"]').click();
 await p.locator('[data-testid="tester-blocked"]').waitFor({state:'visible'});
 await p.locator('[data-testid="tester-blocked"] [data-h="0"]').click();
 await p.locator('[data-testid="tester-blocked"]').waitFor({state:'detached'});
 await p.evaluate(()=>window.ELDORIA_TESTER.ask({id:'qa-negative',question:'¿Entendiste esta prueba?',reasons:['R1','R2','R3','Otro']}));
 await p.locator('[data-testid="tester-question-qa-negative"]').waitFor({state:'visible'});
 await p.locator('[data-testid="tester-question-qa-negative"] [data-a="No"]').click();
 await p.locator('[data-testid="tester-question-qa-negative"] [data-r="1"]').click();
 await p.locator('[data-testid="tester-question-qa-negative"]').waitFor({state:'detached'});
 await p.evaluate(async()=>{window.__ELDORIA_TESTER_SUBMIT__=async()=>{throw Error('offline')};await window.ELDORIA_TESTER.submit('qa-offline','Offline','No',{kind:'qa'})});
 let queued=await p.evaluate(()=>window.ELDORIA_TESTER.queue().length);if(queued<1)throw Error('Offline queue did not persist');
 await p.evaluate(async()=>{window.__ELDORIA_TESTER_SUBMIT__=async r=>{window.__testerReceived.push(r);return true};await window.ELDORIA_TESTER.flush()});
 queued=await p.evaluate(()=>window.ELDORIA_TESTER.queue().length);if(queued!==0)throw Error('Offline queue did not flush');
 await p.evaluate(()=>window.ELDORIA_TESTER.openFinal());
 await p.locator('[data-testid="tester-final"]').waitFor({state:'visible'});
 const rows=p.locator('[data-testid="tester-final"] .testerFinalQ');
 if(await rows.count()!==10)throw Error('Final survey must have 10 one-tap questions');
 for(let i=0;i<10;i++)await rows.nth(i).locator('[data-v="Sí"]').click();
 await p.locator('[data-open="favorite"]').fill('QA favorito');
 await p.locator('[data-open="change"]').fill('QA cambio');
 await p.locator('[data-finish]').click();
 await p.locator('[data-testid="tester-final"] .testerDone').waitFor({state:'visible'});
 const received=await p.evaluate(()=>window.__testerReceived);
 if(received.length<15)throw Error('Expected end-to-end feedback records, got '+received.length);
 for(const r of received){if(!r.session_id||!r.question_id||!r.context||!r.context.screen||!r.context.timestamp)throw Error('Feedback context incomplete for '+r.question_id)}
 await p.reload({waitUntil:'domcontentloaded'});
 if(await p.locator('[data-testid="tester-intro"]').count())throw Error('Tester intro repeated after first launch');
 await p.locator('[data-testid="tester-feedback"]').waitFor({state:'visible'});
 const dims=await p.evaluate(()=>({w:document.documentElement.scrollWidth,cw:document.documentElement.clientWidth,q:window.ELDORIA_TESTER.queue().length}));
 if(dims.w>dims.cw+2)throw Error('Mobile horizontal overflow '+JSON.stringify(dims));
 if(dims.q!==0)throw Error('Queue unexpectedly non-empty after reload');
 await p.evaluate(async()=>{delete window.__ELDORIA_TESTER_SUBMIT__;await window.ELDORIA_TESTER.submit('qa-real-backend','Real backend persistence QA','PASS',{kind:'qa-backend'});const f=await window.ELDORIA_TESTER.flush();if(f.pending)throw Error('Real backend feedback remained queued')});
 await b.close();
 console.log('CLOSED TESTER LAYER QA PASS');
})().catch(e=>{console.error(e);process.exit(1)});