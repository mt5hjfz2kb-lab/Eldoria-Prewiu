const {chromium}=require('playwright');
(async()=>{
 const b=await chromium.launch({headless:true});
 const p=await b.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const URL=process.env.ELDORIA_URL||'http://127.0.0.1:4173/playtest/?qa=1';
 await p.goto(URL,{waitUntil:'domcontentloaded'});
 const now=Date.now();
 await p.evaluate(({now})=>window.ELDORIA_V023.setQA({wood:100,forestRemain:1250,sawmill:true,lastPassiveAt:now,tasks:[{key:'gather-forest',title:'RECOLECTANDO MADERA',target:'forest',start:now-1000,end:now+700}]}),{now});
 const pre=await p.evaluate(()=>window.ELDORIA_V023.state());
 if(!pre.tasks.some(t=>t.key==='gather-forest'))throw Error('Offline test task did not persist before closing');
 await p.goto('about:blank');
 await p.waitForTimeout(1100);
 await p.goto(URL,{waitUntil:'domcontentloaded'});
 const post=await p.evaluate(()=>window.ELDORIA_V023.state());
 console.log('OFFLINE ISOLATED',JSON.stringify({pre,post}));
 if(post.tasks.some(t=>t.key==='gather-forest'))throw Error('Expired gather remained pending');
 if(post.wood<=pre.wood)throw Error('Expired gather did not credit wood');
 if(post.forestRemain>=pre.forestRemain)throw Error('Expired gather did not reduce node');
 await b.close();
 console.log('OFFLINE ISOLATED PASS');
})().catch(e=>{console.error(e);process.exit(1)});