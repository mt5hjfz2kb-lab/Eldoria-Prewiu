const {chromium}=require('playwright');
(async()=>{
  const b=await chromium.launch({headless:true});
  const p=await b.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  await p.goto(process.env.ELDORIA_URL||'http://127.0.0.1:4173/playtest/?qa=1',{waitUntil:'domcontentloaded'});
  await p.evaluate(()=>{localStorage.setItem('eldoria-aldric-story-r7-v3','1');document.querySelectorAll('.aldric-cinematic,.e22-overlay').forEach(x=>x.remove())});
  const set=x=>p.evaluate(v=>window.ELDORIA_V023.setQA(v),x);
  const state=()=>p.evaluate(()=>window.ELDORIA_V023.state());
  await set({introSeen:true,view:'kingdom',chestUnlocked:true,inventory:[{id:'test-material',name:'Fragmento de prueba',type:'material',copy:'Material QA'}],codexUnlocked:true,orusMet:true,duelUnlocked:false,duelSeen:false,cardChoices:{},cardsConsumed:[],cardCooldowns:{},codex:[{id:'ash-sigil',name:'Sello de Ceniza',rarity:'Rara',quality:'Indestructible',values:{N:3,S:1,E:4,O:2},copy:'Una lámina oscura marcada con cuatro direcciones.'},{id:'qa-relic',name:'Reliquia QA',rarity:'Común',values:{N:2,S:2,E:2,O:2},copy:'Carta consumible de prueba.'}],wood:9999,stone:100,food:9999,bastionLevel:7});
  const chest=p.locator('[data-testid="valoria-chest"]');
  await chest.tap({force:true});
  await p.locator('.archiveScene.chestScene').waitFor({state:'visible',timeout:4000});
  if(await p.locator('.e22-overlay:visible').count())throw Error('Chest opened as overlay instead of full scene');
  if((await state()).view!=='chest')throw Error('Chest did not become a dedicated view');
  await p.locator('[data-testid="nav-codex"]').tap({force:true});
  await p.locator('.archiveScene.codexScene').waitFor({state:'visible',timeout:4000});
  if(await p.locator('.e22-overlay:visible').count())throw Error('Codex opened as overlay instead of full scene');
  const expl=await p.locator('[data-testid="codex-use-keep-explainer"]').innerText();
  for(const term of ['USAR','CONSERVAR','consume','Eco 1/1/1/1','INDESTRUCTIBLE','enfriamiento'])if(!expl.toLowerCase().includes(term.toLowerCase()))throw Error('Codex decision explanation missing '+term);
  const before=await state();
  await p.locator('[data-testid="card-use-ash-sigil"]').tap({force:true});
  await p.locator('.e22-overlay:visible .btn').tap({force:true}).catch(()=>{});
  const after=await state();
  if(after.stone<before.stone+260)throw Error('Indestructible relic effect did not apply');
  if(!after.codex.some(x=>x.id==='ash-sigil'))throw Error('Indestructible relic was consumed');
  if(!(after.cardCooldowns&&after.cardCooldowns['ash-sigil']>Date.now()))throw Error('Indestructible relic did not enter cooldown');
  await p.evaluate(()=>window.ELDORIA_V023.setQA({view:'codex'}));
  await p.locator('[data-testid="card-use-qa-relic"]').tap({force:true});
  await p.locator('.e22-overlay:visible .btn').tap({force:true}).catch(()=>{});
  const consumed=await state();
  if(consumed.codex.some(x=>x.id==='qa-relic'))throw Error('Normal relic was not consumed');
  if(!(consumed.cardsConsumed||[]).includes('qa-relic'))throw Error('Consumed relic did not leave an Echo/discovery record');
  await p.evaluate(()=>window.ELDORIA_V023.setQA({view:'codex',cardChoices:{},cardCooldowns:{}}));
  await p.locator('[data-testid="card-keep-ash-sigil"]').tap({force:true});
  await p.locator('.e22-overlay:visible .btn').tap({force:true}).catch(()=>{});
  if((await state()).cardChoices['ash-sigil']!=='keep')throw Error('Keep relic decision did not persist');
  await p.locator('[data-testid="open-relic-training"]').tap({force:true});
  await p.locator('.duel026').waitFor({state:'visible',timeout:4000});
  await p.locator('[data-dir="E"]').tap({force:true});
  const result=await p.locator('[data-duel-result]').innerText();
  if(!/CAPTURA/.test(result))throw Error('Relic Duel orientation rule did not resolve');
  if(!(await state()).duelSeen)throw Error('Relic Duel training completion did not persist');
  await p.locator('.duel026 [data-close]').tap({force:true});
  await set({view:'codex',cardsConsumed:['echo-a','echo-b','echo-c','echo-d'],cardChoices:{'ash-sigil':'keep'},cardCooldowns:{}});
  await p.locator('[data-testid="open-relic-duel"]').tap({force:true});
  await p.locator('.duelFormal026 .duelGrid026').waitFor({state:'visible',timeout:4000});
  if(await p.locator('.duelCell026').count()!==9)throw Error('Formal Relic Duel is not a 3x3 board');
  await p.locator('[data-duel-hand="0"]').tap({force:true});
  await p.locator('[data-duel-cell="4"]').tap({force:true});
  await p.waitForTimeout(700);
  if(await p.locator('.duelCell026.player,.duelCell026.cpu').count()<2)throw Error('Formal Relic Duel did not resolve player + Orus turns');
  const formalText=await p.locator('.duelFormal026').innerText();
  for(const term of ['+1','Ecos 1/1/1/1','N','E','S','O'])if(!formalText.includes(term))throw Error('Formal duel rule surface missing '+term);
  await b.close();
  console.log('CODEX + CHEST v0.26.4 PASS');
})().catch(e=>{console.error(e);process.exit(1)});