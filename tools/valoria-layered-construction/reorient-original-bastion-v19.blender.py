def reflect_native_bmesh_y(ob):
 """Actual editable DCC mesh operation, not a Unity object transform.
 Mirroring local vertices about WORLD Y midpoint and reversing winding maintains
 outward normals and exact same world AABB, while reversing authored facade side.
 """
 lo,hi=bounds(ob)
 mid=(lo[1]+hi[1])*.5
 m=ob.matrix_world
 inv=m.inverted()
 bm=bmesh.new();bm.from_mesh(ob.data)
 old_faces=len(bm.faces)
 for v in bm.verts:
  world=m@v.co
  world.y=2*mid-world.y
  v.co=inv@world
 for f in bm.faces:f.normal_flip()
 bm.normal_update();bm.to_mesh(ob.data);bm.free();ob.data.update()
 assert len(ob.data.polygons)==old_faces
 return mid
