  try:
   with urllib.request.urlopen(request,timeout=a.request_timeout) as response:reply=json.load(response)
  except urllib.error.HTTPError as exc:
   details=exc.read(2048).decode('utf8','replace')
   raise RuntimeError(f'Local Ollama HTTP {exc.code} on artist attempt {attempt_index+1}: {details}') from exc
  inference_seconds=round(time.monotonic()-started,3)
  total_inference_seconds+=inference_seconds
  raw_content=reply.get('message',{}).get('content','')
  if not isinstance(raw_content,str) or not raw_content:raise ValueError('Local artist returned empty response; no geometry was executed')
