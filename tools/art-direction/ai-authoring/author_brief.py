#!/usr/bin/env python3
"""Create REAL scene-aware Qwen artistic direction using local Ollama and versioned system role.
Requires two genuine images; it does not execute Blender or certify art by itself.
"""
import argparse,base64,hashlib,json,pathlib,urllib.request,urllib.parse,urllib.error,time
from artist_plan_validation import inspect_artist_plan,bounded_repair_feedback
HERE=pathlib.Path(__file__).resolve().parent
ALLOWED={'sculpt_region','reprofile_crest','sculpt_path','bridge_boundary_loops','construct_mesh','assign_material','place_existing_asset'}
def digest(data):return hashlib.sha256(data).hexdigest()

def cpu_artist_schema(target,mode,max_actions):
 """Constrain output *shape*, never prescribe artistic coordinates or geometry."""
 kinds=['sculpt_region','sculpt_path','reprofile_crest','bridge_boundary_loops','assign_material','place_existing_asset'] if mode=='existing' else ['construct_mesh','sculpt_region','sculpt_path','reprofile_crest','assign_material']
 if mode=='existing' and max_actions<=2:
  # For an existing cliff, avoid repeating enormous invented mesh face lists.
  kinds=['sculpt_region','sculpt_path','reprofile_crest']
 fields={
  'observed_defect':{'type':'string','minLength':35,'maxLength':250},
  'design_intent':{'type':'string','minLength':35,'maxLength':260},
  'asset_decision':{'type':'string','enum':['REUSE','MODIFY'] if mode=='existing' else ['NEW']},
  'reason_for_new_geometry':{'type':'string','minLength':12,'maxLength':190},
  'planned_actions':{'type':'array','minItems':1,'maxItems':max_actions,'items':{
   'type':'object','additionalProperties':False,
   'properties':{
    'id':{'type':'string','maxLength':32},
    'type':{'type':'string','enum':kinds},
    'target':{'type':'string','const':target},
    'rationale':{'type':'string','minLength':15,'maxLength':190},
    'parameters':{'type':'object','minProperties':2,'maxProperties':5}
   },'required':['id','type','target','rationale','parameters']}},
  'expected_visual_difference':{'type':'string','maxLength':200},
  'mobile_risks':{'type':'string','maxLength':180}
 }
 return {'type':'object','additionalProperties':False,'properties':fields,'required':list(fields)}

def main():
 p=argparse.ArgumentParser()
 p.add_argument('--reference',type=pathlib.Path,required=True)
 p.add_argument('--unity-before',type=pathlib.Path,required=True)
 p.add_argument('--target-object',required=True)
 p.add_argument('--target-mode',choices=['existing','new'],default='existing',help='new allows the artist to create a previously absent mesh')
 p.add_argument('--inventory',type=pathlib.Path)
 p.add_argument('--mesh-context',type=pathlib.Path,help='Optional existing Blender mesh vertex indices, border loops and anchoring coordinates')
 p.add_argument('--prior-visual-review',type=pathlib.Path,help='Optional real previous Blender matched-camera comparison JSON for Qwen-directed visual correction')
 p.add_argument('--out',required=True,type=pathlib.Path)
 p.add_argument('--model',default='qwen3-vl:4b-instruct')
 p.add_argument('--num-ctx',type=int,default=16384,help='Bound the actual local Ollama context budget')
 p.add_argument('--num-predict',type=int,default=2000,help='Bound tokens generated by local artist')
 p.add_argument('--max-actions',type=int,default=8,help='Keep pilot plans short enough for local CPU models')
 p.add_argument('--cpu-compact',action='store_true',help='Shorten only long inventory/journal/topology context; preserve genuine images, system role and design freedom')
 p.add_argument('--repair-attempts',type=int,choices=(0,1),default=1,help='Allow one NEW Qwen artist decision after typed feedback; never script a fake displacement')
 p.add_argument('--request-timeout',type=int,default=420,help='Local Ollama timeout per independent artist decision (seconds)')
 p.add_argument('--endpoint',default='http://127.0.0.1:11434/api/chat')
 a=p.parse_args()
 if not 4096<=a.num_ctx<=32768 or not 256<=a.num_predict<=3000:raise ValueError('Unsafe local Ollama token budgets')
 if not 1<=a.max_actions<=8:raise ValueError('max-actions must be within 1..8')
 if not 60<=a.request_timeout<=540:raise ValueError('Ollama per-attempt timeout must be 60..540 seconds')
 uri=urllib.parse.urlsplit(a.endpoint)
