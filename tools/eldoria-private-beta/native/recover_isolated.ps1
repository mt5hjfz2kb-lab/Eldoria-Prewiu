param([string]$Tools,[string]$Evidence)
$ErrorActionPreference='Stop'
$source=Join-Path $env:GITHUB_WORKSPACE 'beta-structural-source-42505611257-1'
$warm=Join-Path $env:GITHUB_WORKSPACE 'valoria-layered-source'
$frozen='948ffa9837168a0b68dab80be76b66350422b23a'
if(@(Get-Process Unity,blender -ErrorAction SilentlyContinue).Count){throw 'Native tools busy'}
if((git -C $source rev-parse HEAD).Trim() -ne $frozen){throw 'Recovery source identity mismatch'}
& (Join-Path $Tools 'tools/eldoria-private-beta/native/ux/recover_first_attempt.ps1') -Source $source -Evidence $Evidence
New-Item -ItemType Directory -Force $Evidence|Out-Null
$utf8=New-Object Text.UTF8Encoding($false)
# Resume the exact recovered input only after the prior wrapper proved restoration.
$previous=Join-Path $env:GITHUB_WORKSPACE 'beta-structural-evidence-42507779126-1'
if(Test-Path (Join-Path $previous 'warm-cache-restoration.json')){
 $restored=Get-Content (Join-Path $previous 'warm-cache-restoration.json') -Raw|ConvertFrom-Json
 if(-not $restored.restored){throw 'Prior isolated input was not restored'}
 $pinned=Join-Path $previous 'existing-input-audit.json'
 if((Get-FileHash $pinned -Algorithm SHA256).Hash -ne 'DB0DC33D00DFA620AF5EA2F8B26557C999731F871F85A67A5985E4ECCE866AF0'){throw 'Recovered input audit changed'}
 $auditPath=Join-Path ([IO.Path]::GetFullPath($Evidence)) 'existing-input-audit.json'
 Copy-Item $pinned $auditPath
 # Diagnose a failed prior restoration against the IMMUTABLE original input,
 # before any new PlayMode overlay. Never regenerate the approved baseline.
 $original=Get-Content -LiteralPath $pinned -Raw|ConvertFrom-Json
 $current=@(git -C $source status --porcelain -- Unity)
 $statusExit=$LASTEXITCODE
 $delta=@(Compare-Object @($original.status) $current)
 if($statusExit -ne 0 -or $delta.Count){
  @{
   expected=@($original.status);actual=@($current);git_exit=$statusExit;
   differences=@($delta|ForEach-Object {@{status=$_.InputObject;side=$_.SideIndicator}})
  }|ConvertTo-Json -Depth 6|Set-Content -LiteralPath (Join-Path $Evidence 'recovery-status-delta.json') -Encoding UTF8
  foreach($entry in $delta){
   Write-Host ("PR179_RECOVERY_STATUS_DELTA "+$entry.SideIndicator+" "+$entry.InputObject)
  }
  throw 'Original hot-input status mismatch; diagnostic preserved, no new Unity overlay allowed'
 }
 Add-Content $env:GITHUB_ENV "BETA_SOURCE=$source"
 Add-Content $env:GITHUB_ENV "BETA_INPUT_AUDIT=$auditPath"
 Write-Host 'Reusing exact restored production input; wrapper will verify every current file before Unity'
 return
}
$changes=@(git -C $source -c core.quotepath=false ls-files --modified --others --exclude-standard -- Unity)
# These are the paths generated by the recorded first clean import, not arbitrary source edits.
foreach($path in $changes){
 $allowed=$path -match '^Unity/Assets/NatureStarterKit2/' -or $path -match '^Unity/Assets/Gsplat(\.meta|/)' -or $path -match '^Unity/Assets/Eldoria/Resources/WorldInventory/Materials(\.meta|/)' -or $path -match '^Unity/Assets/Eldoria/(ArtTests/ValoriaReferenceClean/Integration/Resources/BastionIVV/Portraits/[^/]+\.jpeg\.meta|Resources/EldoriaRetention/[^/]+\.png\.meta|UI/ValoriaRoyalHUDV1/Sprites/Recovered/[^/]+\.png\.meta)$'
 if(-not $allowed -or $path -match '\.(cs|dll|asmdef|exe)$'){throw "Unexpected recovery input: $path"}
}
$diff=git -C $source diff -- Unity
[IO.File]::WriteAllText((Join-Path $Evidence 'first-import-normalization.diff'),($diff -join "`n"),$utf8)
# Recover only existing, previously reviewed production art. Shared project remains read-only.
$prior=Get-Content (Join-Path $Tools 'tools/eldoria-private-beta/native/existing-input-audit.json') -Raw|ConvertFrom-Json
if($prior.base -ne $frozen){throw 'Production art audit base mismatch'}
$art=@($prior.files|Where-Object {$_.path.StartsWith('Unity/Assets/Eldoria/ArtTests/ValoriaReferenceClean/Integration/Resources/BastionIII/')})
if($art.Count -lt 10){throw 'Production art inventory incomplete'}
foreach($item in $art){
 $from=Join-Path $warm $item.path
 if(-not(Test-Path $from -PathType Leaf) -or (Get-FileHash $from -Algorithm SHA256).Hash -ne $item.sha256){throw "Production art differs from reviewed hash: $($item.path)"}
}
foreach($item in $art){
 $to=Join-Path $source $item.path
 if(Test-Path $to){throw "Recovery refuses to replace existing art: $($item.path)"}
 New-Item -ItemType Directory -Force (Split-Path $to)|Out-Null
 Copy-Item (Join-Path $warm $item.path) $to
 if((Get-FileHash $to -Algorithm SHA256).Hash -ne $item.sha256){throw 'Recovered art copy hash mismatch'}
}
[IO.File]::WriteAllText((Join-Path $Evidence 'recovered-production-art.json'),($art|ConvertTo-Json -Depth 6),$utf8)
$files=@(git -C $source -c core.quotepath=false ls-files --modified --others --exclude-standard -- Unity|ForEach-Object {@{path=$_;sha256=(Get-FileHash (Join-Path $source $_) -Algorithm SHA256).Hash}})
$audit=@{base=$frozen;status=@(git -C $source status --porcelain -- Unity);files=$files;source_kind='owned isolated import plus hash-verified existing production art';origin_run='42505611257'}
$auditPath=Join-Path ([IO.Path]::GetFullPath($Evidence)) 'existing-input-audit.json'
[IO.File]::WriteAllText($auditPath,($audit|ConvertTo-Json -Depth 6),$utf8)
Add-Content $env:GITHUB_ENV "BETA_SOURCE=$source"
Add-Content $env:GITHUB_ENV "BETA_INPUT_AUDIT=$auditPath"
Write-Host "RECOVERED_PRODUCTION_ART_VERIFIED count=$($art.Count); importer input files=$($files.Count)"
