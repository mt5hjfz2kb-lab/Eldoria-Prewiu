"""Package the exact already-rendered hero source; no extra modelling or CI dispatch."""
import json,struct,hashlib,zipfile,shutil
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
ROOT=Path(__file__).resolve().parents[2]
ASSET=ROOT/'art-source/valoria/production/first-hero-gate-v1'
DOC=ROOT/'docs/evidence/valoria-first-hero-asset-v1'
raw=(ASSET/'ValoriaHeroGate.glb').read_bytes()
assert raw[:4]==b'glTF' and struct.unpack_from('<I',raw,8)[0]==len(raw)
jl=struct.unpack_from('<I',raw,12)[0];g=json.loads(raw[20:20+jl]);bl=struct.unpack_from('<I',raw,20+jl)[0];binary=raw[28+jl:28+jl+bl]
out=ASSET/'textures/embedded';out.mkdir(parents=True,exist_ok=True)
images=[]
for i,im in enumerate(g['images']):
    v=g['bufferViews'][im['bufferView']];off=v.get('byteOffset',0);data=binary[off:off+v['byteLength']]
    ext='.png' if im['mimeType']=='image/png' else '.jpg'
    p=out/(str(i).zfill(2)+'_'+im.get('name','texture').replace('/','_')+ext);p.write_bytes(data)
    images.append({'index':i,'path':str(p.relative_to(ASSET)),'sha256':hashlib.sha256(data).hexdigest()})
(ASSET/'materials.json').write_text(json.dumps({'materials':g['materials'],'textures':g.get('textures',[]),'samplers':g.get('samplers',[]),'images':images,'external_images_note':'Generated by this delivery helper; these same maps are already embedded in the GLB and editable BLEND.'},indent=2))
hashes={p.name:{'sha256':hashlib.sha256(p.read_bytes()).hexdigest(),'bytes':p.stat().st_size} for p in [ASSET/'ValoriaHeroGate.blend',*ASSET.glob('*.glb')]}
(ASSET/'file-hashes.json').write_text(json.dumps(hashes,indent=2))
verification=json.loads((ASSET/'export-verification.json').read_text())
for lod in verification['lods']:
    assert hashes['ValoriaHeroGate_LOD'+str(lod['level'])+'.glb']['sha256']==lod['sha256']
board=Image.new('RGB',(1600,670),'#19202a');draw=ImageDraw.Draw(board)
try:font=ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf',25)
except OSError:font=ImageFont.load_default()
for i,(f,title) in enumerate([('before-v5-matched.png','ANTES - V5'),('after-glb-roundtrip.png','DESPUES - PUERTA HERO / GLB REAL')]):
    im=Image.open(ASSET/f).convert('RGB').resize((800,600));board.paste(im,(i*800,55));draw.text((i*800+20,16),title,font=font,fill='white')
board.save(ASSET/'ValoriaHeroGate_Comparacion.png')
dest=ROOT.parent
shutil.copy2(ASSET/'hero-refine.png',dest/'ValoriaHeroGate_Final.png')
shutil.copy2(ASSET/'ValoriaHeroGate_Comparacion.png',dest/'ValoriaHeroGate_Comparacion.png')
zpath=dest/'ValoriaHeroGate_Entrega.zip'
with zipfile.ZipFile(zpath,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=6) as z:
    for p in sorted(ASSET.rglob('*')):
        if p.is_file() and p.suffix!='.blend1' and 'initial' not in p.name:z.write(p,'ValoriaHeroGate/'+str(p.relative_to(ASSET)))
    for p in sorted(DOC.glob('*')):
        if p.is_file():z.write(p,'Documentacion/'+p.name)
    scripts=[Path(__file__),ROOT/'tools/art-rd/valoria_first_hero_asset.py',*sorted((ROOT/'tools/art-rd/first-hero-support').glob('*.py')),ROOT/'.github/workflows/valoria-first-hero-asset.yml',ROOT/'references/VALORIA_APPROVED_VISUAL_REFERENCE.jpg']
    for p in scripts:z.write(p,'Reproduccion/'+str(p.relative_to(ROOT)))
with zipfile.ZipFile(zpath) as z:assert z.testzip() is None
print(json.dumps({'file':str(zpath),'bytes':zpath.stat().st_size,'source_hashes_verified':True,'zip_valid':True}))
